// for loop-----------------------
for(let i = 0; i < 10; i++) {  // post-increment
    console.log(i);
}

// while loop--------------------
let j = 0;
while(j < 10) {
    console.log(j);
    j++
}

// do-while loop--------------------
let z = 0;
do {
    console.log(z);
    z++;
} while(z < 10);